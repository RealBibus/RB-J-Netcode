package netcore.time;

/** Как движок обрабатывает тик. */
public enum TickMode {

    /**
     * Ввод применяется на границе тика. Проще всего, но при низком тикрейте
     * нажатие «ждёт» до следующего тика.
     */
    FIXED,

    /**
     * Ввод несёт дробное время внутри тика (0..1). Сервер раскладывает ввод
     * по подшагам и применяет в правильном порядке, даже если несколько
     * нажатий пришли за один тик.
     */
    SUBTICK
}
